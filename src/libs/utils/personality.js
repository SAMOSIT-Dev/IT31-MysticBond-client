export function getPersonalityPercentage(selecteds = []) {
  const mapChoicesToColors = selecteds.map((selected) => mapChoiceToColor[selected] ?? "unknown")

  const countingEachColor = mapChoicesToColors.reduce((acc, item) => {
    acc[item] = (acc[item] || 0) + 1;
    return acc;
  }, {})

  const total = Object.values(countingEachColor).reduce((prev, cur) => prev + cur, 0)

  const percentageEachColor = Object.entries(countingEachColor).reduce((acc, [color, count]) => {
    acc[color] = ((count / total) * 100).toFixed(2);
    return acc;
  }, {});

  return percentageEachColor
}